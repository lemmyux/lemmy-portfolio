const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
function dims(file) {
  const out = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', file]).toString();
  return { w: +out.match(/pixelWidth: (\d+)/)[1], h: +out.match(/pixelHeight: (\d+)/)[1] };
}
function pick(html, re, what) {
  const m = html.match(re);
  if (!m) throw new Error('Could not find ' + what);
  return m[1] !== undefined ? m[1] : m[0];
}

function shot(slug, file, alt, eager) {
  const d = dims(path.join(WEBSITE, 'img/work', slug, file));
  const tall = d.h / d.w > 2;
  const img = `<img src="../img/work/${slug}/${file}" alt="${esc(alt)}" width="${d.w}" height="${d.h}"${eager ? '' : ' loading="lazy"'} decoding="async">`;
  if (tall) return `<figure class="shot tall"><div class="hint" aria-hidden="true"><span>Full page</span><span>Scroll inside</span></div>${img}</figure>`;
  return `<figure class="shot">${img}</figure>`;
}

