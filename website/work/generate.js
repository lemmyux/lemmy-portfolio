function lift(site, cfg) {
  const home = fs.readFileSync(path.join(WEBSITE, site.page), 'utf8');
  return {
    fontLink: pick(home, /<link rel="stylesheet" href="https:\/\/fonts\.googleapis\.com\/css2[^"]*">/, 'font link'),
    tokens: pick(home, /:root \{\n(\s+color-scheme: dark;[\s\S]*?)\n\}/, 'tokens'),
    fxCss: pick(home, /(\/\* Cyber FX:[\s\S]*?)<\/style>/, 'FX CSS'),
    soundBtn: pick(home, /<button class="fx-sound"[\s\S]*?<\/button>/, 'sound button'),
    fxJs: pick(home, /<script>\n\/\* Cyber FX: boot sequence[\s\S]*?<\/script>/, 'FX script')
      .replace(/var cfg = \{ glitch: '[^']*', scramble: '[^']*' \};/, `var cfg = { glitch: '${cfg.glitch}', scramble: '${cfg.scramble}' };`),
    soundJs: pick(home, /<script>\n\/\* UI sounds[\s\S]*?<\/script>/, 'sound script'),
  };
}

